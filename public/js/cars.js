  async function rentalParams() {
    const pickup = await ensureLoc($('#pickup'));
    const dropoff = $('#diffDrop').checked ? await ensureLoc($('#dropoff')) : '';
    const req = {
      pickup, dropoff, from: $('#fromDate').value, fromTime: $('#fromTime').value, to: $('#toDate').value, toTime: $('#toTime').value,
      age: $('#age').value, currency: state.currency, childSeats: $('#childSeats').value, gps: $('#gps').checked ? '1' : '', extraDriver: $('#extraDriver').checked ? '1' : '',
    };
    const filters = {
      categories: checked('categories').join(','), transmission: radio('transmission'), minSeats: radio('minSeats'),
      fullInsurance: $('#fullInsurance').checked ? '1' : '', freeCancel: $('#freeCancel').checked ? '1' : '',
      companies: checked('companies').join(','), maxPrice: $('#maxPrice').value, sort: $('#sort').value,
    };
    return { req, all: { ...req, ...filters } };
  }

  async function runRental() {
    const { req, all } = await rentalParams();
    if (!req.pickup) { $('#pickup').focus(); toast(t('car_unknown_loc')); return; }
    state.rental = state.rental || { pending: true };
    setMode('rental');
    $('#results').innerHTML = `<div class="spinner"></div><p class="muted" style="text-align:center">${esc(t('car_searching'))}</p>`;
    const u = new URLSearchParams({ loc: req.pickup, from: req.from, to: req.to });
    if (req.dropoff) u.set('drop', req.dropoff);
    history.replaceState(null, '', '?' + u.toString());
    try {
      const data = await api('/api/cars/search', all);
      state.rental = data; state.rentalReq = req;
      // Şirkət filtri tətbiq olunmayıbsa, siyahını yenilə (başqa ölkəyə keçəndə köhnə şirkətlər qalmasın)
      if (!all.companies) state.companies = new Map(data.sources.map((s) => [s.id, s]));
      $('#pickup').value = data.query.pickup.name; $('#pickup').dataset.id = data.query.pickup.id;
      renderCatFilter(data.categories);
      renderCompanyFilter();
      renderRental(data);
    } catch (err) {
      state.rental = { error: true };
      $('#resTitle').textContent = ''; $('#resSub').textContent = ''; $('#sources').innerHTML = '';
      let msg = err.message;
      // URL-dən gələn, dəstəklənməyən istiqamət (məs. Maldiv) — sahəni təmizlə ki, istifadəçi seçsin
      if ($('#pickup').value === $('#pickup').dataset.id && !/-(apt|city)$/.test($('#pickup').dataset.id)) {
        $('#pickup').value = ''; delete $('#pickup').dataset.id; msg = t('car_unknown_loc');
      }
      $('#results').innerHTML = `<div class="panel empty">${esc(msg)}</div>`;
    }
  }

